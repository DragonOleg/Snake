using System;
using System.Collections.Generic;
using System.Linq;
using Microsoft.EntityFrameworkCore;
using Microsoft.Extensions.Logging;
using Snake.Application.Abstractions;
using Snake.Domain;
using Snake.Persistence.Data;
using Snake.Persistence.Data.Entities;

namespace Snake.Persistence.Repositories
{
    /// <summary>
    /// Реализация портов записи и чтения результатов на PostgreSQL.
    /// Контекст создаётся на каждую операцию, поэтому объект можно держать синглтоном.
    /// </summary>
    public sealed class GameResultRepository : IGameResultSink, IGameResultReader
    {
        private const string SchemaSql = @"
CREATE TABLE IF NOT EXISTS game_results (
    id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    finished_at_utc timestamptz NOT NULL,
    score           integer NOT NULL,
    length          integer NOT NULL,
    level           integer NOT NULL,
    eaten           integer NOT NULL,
    duration_ms     integer NOT NULL,
    board_width     integer NOT NULL,
    board_height    integer NOT NULL,
    outcome         text NOT NULL,
    status_message  text NULL
);
CREATE INDEX IF NOT EXISTS ix_game_results_score ON game_results (score DESC);
CREATE INDEX IF NOT EXISTS ix_game_results_finished_at ON game_results (finished_at_utc DESC);
";

        private readonly DbContextOptions<SnakeDbContext> _options;
        private readonly ILogger<GameResultRepository> _logger;

        public GameResultRepository(string connectionString, ILogger<GameResultRepository> logger = null)
        {
            if (string.IsNullOrWhiteSpace(connectionString))
            {
                throw new ArgumentException("Не задана строка подключения Snake.", nameof(connectionString));
            }

            _logger = logger;
            _options = new DbContextOptionsBuilder<SnakeDbContext>()
                .UseNpgsql(connectionString)
                .Options;
        }

        private SnakeDbContext CreateContext()
        {
            return new SnakeDbContext(_options);
        }

        /// <summary>Создаёт базу (если нет) и идемпотентно создаёт таблицу и индексы.</summary>
        public void EnsureSchema()
        {
            using (SnakeDbContext db = CreateContext())
            {
                db.Database.EnsureCreated();
                db.Database.ExecuteSqlRaw(SchemaSql);
            }
        }

        public void Save(GameRunResult result)
        {
            if (result == null)
            {
                throw new ArgumentNullException(nameof(result));
            }

            using (SnakeDbContext db = CreateContext())
            {
                db.GameResults.Add(ToEntity(result));

                try
                {
                    db.SaveChanges();
                }
                catch (Exception ex)
                {
                    if (_logger != null)
                    {
                        _logger.LogError(ex, "Не удалось записать результат партии");
                    }

                    throw;
                }
            }
        }

        public GameProgress GetProgress()
        {
            using (SnakeDbContext db = CreateContext())
            {
                IQueryable<GameResultEntity> query = db.GameResults.AsNoTracking();
                int games = query.Count();
                if (games == 0)
                {
                    return new GameProgress();
                }

                GameResultEntity last = query
                    .OrderByDescending(x => x.FinishedAtUtc)
                    .ThenByDescending(x => x.Id)
                    .First();

                return new GameProgress
                {
                    Games = games,
                    BestScore = query.Max(x => x.Score),
                    AverageScore = Math.Round(query.Average(x => (double)x.Score), 1),
                    BestLength = query.Max(x => x.Length),
                    BestLevel = query.Max(x => x.Level),
                    TotalEaten = query.Sum(x => x.Eaten),
                    FirstPlayedUtc = query.Min(x => x.FinishedAtUtc),
                    Last = ToModel(last)
                };
            }
        }

        public IReadOnlyList<GameRunResult> GetBest(int count)
        {
            if (count <= 0)
            {
                return new List<GameRunResult>();
            }

            using (SnakeDbContext db = CreateContext())
            {
                return db.GameResults.AsNoTracking()
                    .OrderByDescending(x => x.Score)
                    .ThenBy(x => x.FinishedAtUtc)
                    .Take(count)
                    .ToList()
                    .Select(ToModel)
                    .ToList();
            }
        }

        public IReadOnlyList<GameRunResult> GetRecent(int count)
        {
            if (count <= 0)
            {
                return new List<GameRunResult>();
            }

            using (SnakeDbContext db = CreateContext())
            {
                return db.GameResults.AsNoTracking()
                    .OrderByDescending(x => x.FinishedAtUtc)
                    .ThenByDescending(x => x.Id)
                    .Take(count)
                    .ToList()
                    .Select(ToModel)
                    .ToList();
            }
        }

        private static GameResultEntity ToEntity(GameRunResult result)
        {
            DateTime finished = result.FinishedAtUtc.Kind == DateTimeKind.Utc
                ? result.FinishedAtUtc
                : result.FinishedAtUtc.ToUniversalTime();

            return new GameResultEntity
            {
                FinishedAtUtc = finished,
                Score = result.Score,
                Length = result.Length,
                Level = result.Level,
                Eaten = result.Eaten,
                DurationMs = result.DurationMs,
                BoardWidth = result.BoardWidth,
                BoardHeight = result.BoardHeight,
                Outcome = result.Outcome.ToString(),
                StatusMessage = result.StatusMessage
            };
        }

        private static GameRunResult ToModel(GameResultEntity entity)
        {
            GameState outcome;
            if (!Enum.TryParse(entity.Outcome, true, out outcome))
            {
                outcome = GameState.GameOver;
            }

            return new GameRunResult
            {
                FinishedAtUtc = entity.FinishedAtUtc,
                Score = entity.Score,
                Length = entity.Length,
                Level = entity.Level,
                Eaten = entity.Eaten,
                DurationMs = entity.DurationMs,
                BoardWidth = entity.BoardWidth,
                BoardHeight = entity.BoardHeight,
                Outcome = outcome,
                StatusMessage = entity.StatusMessage
            };
        }
    }
}
